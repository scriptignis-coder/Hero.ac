-- Run in Supabase SQL Editor. Safe to re-run; does not delete existing rows.
-- Matches api/blacklist.js and api/_abuse.js.
CREATE TABLE IF NOT EXISTS public.hs_blacklist (
  discord_id text PRIMARY KEY,
  reason text NOT NULL DEFAULT '',
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by text,
  created_at timestamptz NOT NULL DEFAULT now(),
  lifted_at timestamptz,
  lifted_by text
);
CREATE TABLE IF NOT EXISTS public.hs_abandoned_scans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pin_id text,
  pin text,
  license_id text,
  owner_discord text,
  player text,
  starts integer,
  started_at timestamptz,
  self_scan boolean DEFAULT false,
  noticed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS hs_abandoned_scans_owner_idx ON public.hs_abandoned_scans(owner_discord);
CREATE TABLE IF NOT EXISTS public.hs_settings (
  key text PRIMARY KEY,
  value text NOT NULL
);
